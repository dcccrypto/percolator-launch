import { OrderTicket } from "@/components/trade/OrderTicket";

const SLAB = "CjdnH8fTmxNMsuUevBt9VjSi87E3ESTcuWuoSrjUjvXE";
const MINT = new PublicKey("So11111111111111111111111111111111111111112");

beforeEach(() => {
  vi.clearAllMocks();
  mocks.useWalletCompat.mockReturnValue({ publicKey: new PublicKey("11111111111111111111111111111111"), connected: true });
  mocks.useConnectionCompat.mockReturnValue({
    connection: { getTokenAccountBalance: vi.fn().mockResolvedValue({ value: { amount: "0", decimals: 6 } }) },
  });
  mocks.useSlabState.mockReturnValue({
    accounts: [], config: { collateralMint: MINT, decimals: 6 }, header: null, refresh: vi.fn(),
    programId: new PublicKey("11111111111111111111111111111111"),
  });
  mocks.useEngineState.mockReturnValue({ engine: null, params: { initialMarginBps: 1000n, maintenanceMarginBps: 500n, tradingFeeBps: 30n }, insuranceBalance: 1_000_000n, totalOI: 0n, hasData: true });
});

const submit = () => screen.getByTestId("trade-submit") as HTMLButtonElement;
const size = (v: string) => fireEvent.change(screen.getByTestId("trade-size-input"), { target: { value: v } });
const holding = (positionSize: bigint) =>
  mocks.useUserAccount.mockReturnValue({ account: { capital: 100_000_000n, positionSize, entryPrice: 1_000_000n, pnl: 0n }, idx: 3 });

async function openConfirm(side: "long" | "short", usd: string) {
  render(<OrderTicket slabAddress={SLAB} />);
  await waitFor(() => expect(screen.queryByTestId("trade-submit")).not.toBeNull());
  fireEvent.click(screen.getByTestId(`trade-side-${side}`));
  size(usd);
  await act(async () => fireEvent.click(submit()));
  await waitFor(() => expect(screen.queryByTestId("trade-confirm")).not.toBeNull());
}

describe("Open tab: the confirm heading sees the account's open position", () => {
  it("a 5 short against a 10 long reads 'Reducing Long Position'", async () => {
    holding(10_000_000n);
    await openConfirm("short", "5");
    expect(screen.getByText("Reducing Long Position")).toBeInTheDocument();
  });

  it("CONTROL: flat account, 5 short reads 'Opening Short Position'", async () => {
    holding(0n);
    await openConfirm("short", "5");
    expect(screen.getByText("Opening Short Position")).toBeInTheDocument();
  });
});
