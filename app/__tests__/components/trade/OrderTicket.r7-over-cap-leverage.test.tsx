const submit = () => screen.getByTestId("trade-submit") as HTMLButtonElement;

describe("over-cap leverage guard", () => {
  afterEach(() => { sub1.cap = null; });

  it("a confirm from the render where the cap fell below the chosen leverage sends nothing", async () => {
    sub1.cap = 8;
    await mount();
    fireEvent.change(screen.getByTestId("trade-size-input"), { target: { value: "300" } });
    await waitFor(() => expect(submit().disabled).toBe(false));
    fireEvent.change(screen.getByTestId("trade-leverage-input"), { target: { value: "2.5" } });
    await waitFor(() => expect((screen.getByTestId("trade-leverage-input") as HTMLInputElement).value).toBe("2.5"));
    fireEvent.click(submit());
    await waitFor(() => expect(mocks.modal.props).not.toBeNull());
    const before = mocks.modal.history.length;
    sub1.cap = 1.5; // the cap for this size fell below the 2.5x chosen (the market cap here is 2.81x)
    fireEvent.change(screen.getByTestId("trade-size-input"), { target: { value: "301" } });
    await waitFor(() => expect((screen.getByTestId("trade-leverage-input") as HTMLInputElement).value).toBe("1.5"));
    // The first modal render after the change saw leverage 2.5 against cap 1.5.
    const overCapConfirm = mocks.modal.history[before];
    expect(overCapConfirm).toBeDefined();
    await act(async () => { overCapConfirm(); });
    expect(mocks.fundAndTrade).not.toHaveBeenCalled();
  });
});
